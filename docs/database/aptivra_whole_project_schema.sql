 ELSIF NEW.state='failed' THEN
  UPDATE report_credit_reservations SET status='released',finalized_at=CURRENT_TIMESTAMP,release_reason='processing_failed'
   WHERE id=NEW.credit_reservation_id AND status='reserved';
 END IF;
 RETURN NEW;
END $$;

