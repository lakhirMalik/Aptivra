   RAISE EXCEPTION 'shared workspace closure requires its owner'; END IF;
  IF NEW.export_artifact_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM stored_artifacts a JOIN retention_scopes s ON s.id=a.retention_scope_id
    WHERE a.id=NEW.export_artifact_id AND a.kind='export' AND s.purpose='export' AND s.owner_user_id=NEW.requester_user_id) THEN RAISE EXCEPTION 'export artifact ownership mismatch'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION preserve_owner_on_account_close() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE orgid bigint;
BEGIN
 IF NEW.status='closed' THEN
  FOR orgid IN SELECT organization_id FROM memberships WHERE user_id=NEW.id AND role='owner' AND status='active' LOOP
   IF EXISTS(SELECT 1 FROM organizations WHERE id=orgid AND status<>'closed') AND NOT EXISTS(
     SELECT 1 FROM memberships m JOIN users u ON u.id=m.user_id WHERE m.organization_id=orgid AND m.role='owner' AND m.status='active' AND u.status='active' AND u.id<>NEW.id) THEN
    RAISE EXCEPTION 'sole owner account needs ownership transfer or explicit workspace closure'; END IF;
  END LOOP;
 END IF;
 RETURN NULL;
