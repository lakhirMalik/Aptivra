CREATE FUNCTION validate_auxiliary_scope() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record;
BEGIN
 IF TG_TABLE_NAME='notifications' THEN
  IF NEW.retention_scope_id IS NOT NULL THEN
   SELECT * INTO x FROM retention_scopes WHERE id=NEW.retention_scope_id;
