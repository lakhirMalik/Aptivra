CREATE FUNCTION validate_report_revision() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record; z record; doc_old bigint; doc_new bigint; nextrev integer;
BEGIN
 IF TG_TABLE_NAME='comparison_corrections' THEN
  SELECT * INTO x FROM evidence_comparisons WHERE id=NEW.comparison_id;
  IF x.state<>'building' OR NOT EXISTS(SELECT 1 FROM cv_extraction_corrections c JOIN cv_passages p ON p.id=c.source_passage_id
    WHERE c.id=NEW.correction_id AND c.status='approved' AND p.cv_extraction_id=x.cv_extraction_id) THEN
   RAISE EXCEPTION 'comparison amendments must be approved and tied to this exact source version'; END IF;
  RETURN NEW;
 END IF;
 SELECT r.*,a.retention_scope_id,s.owner_user_id,s.access_until,s.revoked_at INTO x FROM preparation_reports r
  JOIN stored_artifacts a ON a.id=r.artifact_id JOIN retention_scopes s ON s.id=a.retention_scope_id
  WHERE r.id=NEW.preparation_report_id FOR UPDATE OF r;
 SELECT * INTO y FROM evidence_comparisons WHERE id=x.comparison_id;
 SELECT * INTO z FROM evidence_comparisons WHERE id=NEW.comparison_id;
 SELECT op.cv_document_id INTO doc_old FROM cv_extractions e JOIN processing_operations op ON op.id=e.processing_operation_id WHERE e.id=y.cv_extraction_id;
 SELECT op.cv_document_id INTO doc_new FROM cv_extractions e JOIN processing_operations op ON op.id=e.processing_operation_id WHERE e.id=z.cv_extraction_id;
 IF x.state<>'ready' OR NEW.created_by<>x.owner_user_id OR x.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.access_until
   OR z.state<>'ready' OR doc_old IS DISTINCT FROM doc_new
   OR (y.role_catalogue_version_id,y.vacancy_version_id) IS DISTINCT FROM (z.role_catalogue_version_id,z.vacancy_version_id)
   OR NOT EXISTS(SELECT 1 FROM stored_artifacts WHERE id=NEW.artifact_id AND retention_scope_id=x.retention_scope_id AND kind='report') THEN
  RAISE EXCEPTION 'report revision must preserve owned source, target, purpose and original expiry'; END IF;
 SELECT coalesce(max(revision_number),1)+1 INTO nextrev FROM report_revisions WHERE preparation_report_id=x.id;
 IF NEW.revision_number<>nextrev THEN RAISE EXCEPTION 'report revision sequence is stale'; END IF;
 RETURN NEW;
END $$;
