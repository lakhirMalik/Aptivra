CREATE FUNCTION validate_allowances() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE orgid bigint; u bigint; x record; y record; allowed integer; used integer;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'campaign_allowances' THEN
  SELECT organization_id INTO orgid FROM vacancies WHERE id=NEW.vacancy_id;
  IF TG_OP='UPDATE' THEN
   IF (NEW.vacancy_id,NEW.first_published_at,NEW.grant_kind) IS DISTINCT FROM (OLD.vacancy_id,OLD.first_published_at,OLD.grant_kind)
      OR NEW.intake_deadline<OLD.intake_deadline THEN RAISE EXCEPTION 'campaign identity/first publication cannot reset'; END IF;
   IF NEW.accepted_count IS DISTINCT FROM OLD.accepted_count AND pg_trigger_depth()<2 THEN RAISE EXCEPTION 'accepted count changes only with accepted submissions'; END IF;
   RETURN NEW;
  END IF;
  IF NOT EXISTS(SELECT 1 FROM organizations WHERE id=orgid AND status='approved') THEN RAISE EXCEPTION 'approved organization required'; END IF;
  SELECT * INTO x FROM organization_trial_ledger WHERE organization_id=orgid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'bounded minimal trial ledger must be configured'; END IF;
  IF NEW.grant_kind='trial' THEN
   IF x.free_campaign_vacancy_id IS NOT NULL THEN RAISE EXCEPTION 'free campaign already used'; END IF;
   UPDATE organization_trial_ledger SET free_campaign_vacancy_id=NEW.vacancy_id,used_at=NEW.first_published_at WHERE id=x.id;
  ELSIF NOT EXISTS(SELECT 1 FROM demonstration_entitlements e WHERE e.id=NEW.entitlement_id AND e.organization_id=orgid
    AND e.feature IN ('additional_campaign','campaign_capacity') AND CURRENT_TIMESTAMP>=e.starts_at AND CURRENT_TIMESTAMP<e.expires_at) THEN
   RAISE EXCEPTION 'valid demonstration upgrade required'; END IF;
 WHEN 'campaign_submissions' THEN
  SELECT ca.*,v.status,v.effective_version_id,o.status AS org_status INTO x
   FROM campaign_allowances ca JOIN vacancies v ON v.id=ca.vacancy_id JOIN organizations o ON o.id=v.organization_id
   WHERE ca.id=NEW.campaign_allowance_id FOR UPDATE OF ca;
  IF x.status<>'open' OR x.org_status<>'approved' OR CURRENT_TIMESTAMP>=x.intake_deadline OR x.accepted_count>=x.acceptance_limit THEN
   RAISE EXCEPTION 'campaign closed or full'; END IF;
  IF NOT EXISTS(SELECT 1 FROM users WHERE id=NEW.candidate_user_id AND status='active' AND email_verified_at IS NOT NULL) THEN
   RAISE EXCEPTION 'verified candidate required'; END IF;
  IF NEW.retain_until<x.intake_deadline THEN RAISE EXCEPTION 'submission ledger cannot expire during campaign intake'; END IF;
  UPDATE campaign_allowances SET accepted_count=accepted_count+1 WHERE id=x.id;
 WHEN 'report_credit_reservations' THEN
  SELECT * INTO x FROM report_credit_periods WHERE id=NEW.period_id FOR UPDATE;
  IF TG_OP='INSERT' THEN
   IF NEW.status<>'reserved' OR NEW.reservation_expires_at<=CURRENT_TIMESTAMP THEN RAISE EXCEPTION 'valid reservation required'; END IF;
   IF date_trunc('month',CURRENT_TIMESTAMP AT TIME ZONE x.month_time_zone)::date<>x.month_start THEN RAISE EXCEPTION 'wrong calendar credit period'; END IF;
   allowed:=x.base_allowance;
   IF x.additional_entitlement_id IS NOT NULL THEN
    SELECT quantity INTO used FROM demonstration_entitlements WHERE id=x.additional_entitlement_id AND user_id=x.user_id
      AND feature='report_credits' AND CURRENT_TIMESTAMP>=starts_at AND CURRENT_TIMESTAMP<expires_at;
    IF NOT FOUND THEN RAISE EXCEPTION 'invalid additional credit entitlement'; END IF;
    allowed:=allowed+used;
   END IF;
   SELECT count(*) INTO used FROM report_credit_reservations WHERE period_id=x.id AND
     (status='consumed' OR (status='reserved' AND reservation_expires_at>CURRENT_TIMESTAMP));
   IF used>=allowed THEN RAISE EXCEPTION 'report allowance exhausted'; END IF;
  ELSE
   IF (NEW.period_id,NEW.operation_key,NEW.reserved_at,NEW.reservation_expires_at) IS DISTINCT FROM
      (OLD.period_id,OLD.operation_key,OLD.reserved_at,OLD.reservation_expires_at) OR OLD.status='consumed' THEN
     RAISE EXCEPTION 'reservation identity/finalization is immutable'; END IF;
   IF OLD.status='released' THEN
    IF NEW.status<>'reserved' OR CURRENT_TIMESTAMP>=NEW.reservation_expires_at THEN RAISE EXCEPTION 'retry reservation is expired or invalid'; END IF;
    SELECT count(*) INTO used FROM report_credit_reservations WHERE period_id=x.id AND id<>NEW.id
      AND (status='consumed' OR (status='reserved' AND reservation_expires_at>CURRENT_TIMESTAMP));
    allowed:=x.base_allowance+coalesce((SELECT quantity FROM demonstration_entitlements WHERE id=x.additional_entitlement_id AND feature='report_credits' AND user_id=x.user_id AND CURRENT_TIMESTAMP>=starts_at AND CURRENT_TIMESTAMP<expires_at),0);
    IF used>=allowed THEN RAISE EXCEPTION 'report allowance exhausted'; END IF;
   END IF;
   IF NEW.status='consumed' AND (CURRENT_TIMESTAMP>=NEW.reservation_expires_at OR NOT EXISTS(SELECT 1 FROM preparation_reports WHERE credit_reservation_id=NEW.id AND state='ready')) THEN
    RAISE EXCEPTION 'consume only once for usable ready report'; END IF;
  END IF;
 END CASE;
 RETURN NEW;
END $$;
