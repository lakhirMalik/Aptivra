CREATE FUNCTION validate_application_data() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record; z record; current_revision integer;
BEGIN
 IF TG_TABLE_NAME='applications' THEN
  IF TG_OP='UPDATE' THEN
   IF pg_trigger_depth()<2 OR (NEW.submission_id,NEW.vacancy_version_id,NEW.cv_document_id,NEW.retention_scope_id,NEW.submitted_at)
      IS DISTINCT FROM (OLD.submission_id,OLD.vacancy_version_id,OLD.cv_document_id,OLD.retention_scope_id,OLD.submitted_at) THEN
    RAISE EXCEPTION 'application snapshot is fixed; workflow changes require attributable events'; END IF;
   RETURN NEW;
  END IF;
  SELECT cs.candidate_user_id,cs.accepted_at,ca.vacancy_id,v.organization_id,v.effective_version_id INTO x
   FROM campaign_submissions cs JOIN campaign_allowances ca ON ca.id=cs.campaign_allowance_id
   JOIN vacancies v ON v.id=ca.vacancy_id WHERE cs.id=NEW.submission_id;
  SELECT * INTO y FROM retention_scopes WHERE id=NEW.retention_scope_id;
  SELECT * INTO z FROM document_context WHERE document_id=NEW.cv_document_id;
  IF x.effective_version_id IS DISTINCT FROM NEW.vacancy_version_id OR NOT EXISTS(SELECT 1 FROM vacancy_versions WHERE id=NEW.vacancy_version_id AND vacancy_id=x.vacancy_id AND state='published') THEN
   RAISE EXCEPTION 'application must bind the effective version of its campaign'; END IF;
  IF y.purpose<>'application' OR y.owner_user_id IS DISTINCT FROM x.candidate_user_id OR y.organization_id IS DISTINCT FROM x.organization_id
    OR z.retention_scope_id IS DISTINCT FROM y.id OR NEW.status<>'submitted' OR NEW.first_closed_at IS NOT NULL THEN
   RAISE EXCEPTION 'application owner/document/retention context mismatch'; END IF;
  IF NEW.submitted_at IS DISTINCT FROM x.accepted_at OR y.started_at IS DISTINCT FROM x.accepted_at THEN
   RAISE EXCEPTION 'application retention must start at its atomic accepted submission'; END IF;
  IF NOT EXISTS(SELECT 1 FROM processing_operations op JOIN virus_scan_logs vs ON vs.processing_operation_id=op.id
    WHERE op.cv_document_id=NEW.cv_document_id AND vs.result='clean' AND op.status IN ('ready','needs_clarification')) THEN
   RAISE EXCEPTION 'usable clean submitted CV required'; END IF;
  RETURN NEW;
 END IF;
 PERFORM 1 FROM applications WHERE id=NEW.application_id FOR UPDATE;
 SELECT * INTO x FROM application_context WHERE id=NEW.application_id;
 IF x.id IS NULL THEN RAISE EXCEPTION 'application missing'; END IF;
 SELECT * INTO y FROM retention_scopes WHERE id=x.retention_scope_id;
 IF y.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=y.access_until THEN RAISE EXCEPTION 'application access expired'; END IF;
 CASE TG_TABLE_NAME
 WHEN 'application_reviews' THEN
  IF NOT can_org(NEW.assigned_by,x.organization_id,'review_assign') OR NEW.assigned_by=x.candidate_user_id
   OR NOT can_org(NEW.assigned_to,x.organization_id,'review_complete') OR NEW.assigned_to=x.candidate_user_id
   OR NOT EXISTS(SELECT 1 FROM vacancy_review_stages WHERE id=NEW.stage_id AND vacancy_version_id=x.vacancy_version_id AND stage_type='review') THEN
   RAISE EXCEPTION 'review assignment actor/stage mismatch or self-review'; END IF;
 WHEN 'stage_exceptions' THEN
  IF NOT EXISTS(SELECT 1 FROM vacancy_review_stages WHERE id=NEW.stage_id AND vacancy_version_id=x.vacancy_version_id AND is_required) THEN
   RAISE EXCEPTION 'exception requires a required stage from submitted policy'; END IF;
  IF NEW.requested_by=x.candidate_user_id OR NOT can_org(NEW.requested_by,x.organization_id,'exception_request') THEN RAISE EXCEPTION 'exception requester not authorized'; END IF;
  IF NEW.status<>'pending' AND (NEW.decided_by=x.candidate_user_id OR NOT can_org(NEW.decided_by,x.organization_id,'exception_approve')) THEN
   RAISE EXCEPTION 'exception approver not authorized'; END IF;
  IF TG_OP='UPDATE' AND (OLD.status<>'pending' OR (NEW.application_id,NEW.stage_id,NEW.requested_by,NEW.request_reason,NEW.requested_at)
    IS DISTINCT FROM (OLD.application_id,OLD.stage_id,OLD.requested_by,OLD.request_reason,OLD.requested_at)) THEN
   RAISE EXCEPTION 'resolved exception is immutable; append a new request'; END IF;
 WHEN 'application_referrals' THEN
  IF NEW.recorded_by<>x.candidate_user_id AND NOT can_org(NEW.recorded_by,x.organization_id,'referral_manage') THEN RAISE EXCEPTION 'source recorder not authorized'; END IF;
  IF NEW.status='confirmed' AND (NEW.confirmed_by=x.candidate_user_id OR NOT can_org(NEW.confirmed_by,x.organization_id,'referral_confirm')) THEN
   RAISE EXCEPTION 'source confirmation requires an authorized non-applicant'; END IF;
  SELECT max(revision_number) INTO current_revision FROM application_referrals WHERE application_id=x.id;
  IF NEW.revision_number<>coalesce(current_revision,0)+1 THEN RAISE EXCEPTION 'source revision must follow current history'; END IF;
  IF current_revision IS NOT NULL AND NOT EXISTS(SELECT 1 FROM application_referrals WHERE id=NEW.amends_id AND application_id=x.id AND revision_number=current_revision) THEN
   RAISE EXCEPTION 'source amendment must identify its previous entry'; END IF;
 WHEN 'professional_references' THEN
  IF NEW.recorded_by<>x.candidate_user_id AND NOT can_org(NEW.recorded_by,x.organization_id,'referral_manage') THEN RAISE EXCEPTION 'reference recorder not authorized'; END IF;
 WHEN 'assessment_invitations' THEN
  IF TG_OP='UPDATE' AND (NEW.application_id,NEW.assessment_version_id,NEW.stage_id,NEW.issued_by,NEW.token_hash,NEW.operation_key,NEW.issued_at,NEW.expires_at,NEW.accommodated_duration_seconds)
   IS DISTINCT FROM (OLD.application_id,OLD.assessment_version_id,OLD.stage_id,OLD.issued_by,OLD.token_hash,OLD.operation_key,OLD.issued_at,OLD.expires_at,OLD.accommodated_duration_seconds) THEN
   RAISE EXCEPTION 'issued invitation candidate/version/timing cannot change'; END IF;
  IF x.first_closed_at IS NOT NULL OR x.status IN ('withdrawn','expired') OR NEW.issued_by=x.candidate_user_id
    OR NOT can_org(NEW.issued_by,x.organization_id,'assessment_invite') THEN RAISE EXCEPTION 'new assessment invitation not allowed'; END IF;
  IF NOT EXISTS(SELECT 1 FROM assessment_versions av JOIN assessments a ON a.id=av.assessment_id
   WHERE av.id=NEW.assessment_version_id AND av.state='published' AND a.vacancy_id=x.vacancy_id) THEN
   RAISE EXCEPTION 'assessment version belongs to another vacancy or is unpublished'; END IF;
  IF NEW.stage_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vacancy_review_stages WHERE id=NEW.stage_id AND vacancy_version_id=x.vacancy_version_id AND stage_type='assessment') THEN
   RAISE EXCEPTION 'assessment stage mismatch'; END IF;
 WHEN 'interview_schedules' THEN
  IF x.first_closed_at IS NOT NULL OR x.status IN ('withdrawn','expired') OR NEW.created_by=x.candidate_user_id OR NOT can_org(NEW.created_by,x.organization_id,'interview_manage') THEN
   RAISE EXCEPTION 'new interview not permitted'; END IF;
  IF NEW.stage_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vacancy_review_stages WHERE id=NEW.stage_id AND vacancy_version_id=x.vacancy_version_id AND stage_type='interview') THEN
   RAISE EXCEPTION 'interview stage mismatch'; END IF;
 END CASE;
 RETURN NEW;
END $$;

