CREATE FUNCTION mandatory_stages_satisfied(appid bigint) RETURNS boolean LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE a record; st record;
BEGIN
 SELECT * INTO a FROM application_context WHERE id=appid;
 FOR st IN SELECT * FROM vacancy_review_stages WHERE vacancy_version_id=a.vacancy_version_id AND is_required LOOP
  IF EXISTS(SELECT 1 FROM stage_exceptions WHERE application_id=appid AND stage_id=st.id AND status='approved') THEN CONTINUE; END IF;
  IF st.stage_type='review' AND NOT EXISTS(SELECT 1 FROM application_reviews r JOIN review_events e ON e.review_id=r.id
    WHERE r.application_id=appid AND r.stage_id=st.id AND e.event_type='completed') THEN RETURN false;
  ELSIF st.stage_type='assessment' AND NOT EXISTS(SELECT 1 FROM assessment_invitations i JOIN assessment_attempts at ON at.invitation_id=i.id
    WHERE i.application_id=appid AND i.stage_id=st.id AND i.cancelled_at IS NULL AND at.status='finalized') THEN RETURN false;
  ELSIF st.stage_type='interview' AND NOT EXISTS(SELECT 1 FROM interview_schedules i
    JOIN LATERAL(SELECT coalesce(e.effective_status,e.event_type) AS effective FROM interview_events e WHERE e.interview_id=i.id
     AND e.event_type IN ('scheduled','rescheduled','cancelled','completed','no_show','correction') ORDER BY revision_number DESC LIMIT 1) latest ON true
    WHERE i.application_id=appid AND i.stage_id=st.id AND latest.effective='completed') THEN RETURN false;
  END IF;
 END LOOP;
 RETURN true;
END $$;

CREATE FUNCTION apply_application_event() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE a record; s record; firstclose timestamptz;
BEGIN
 SELECT * INTO a FROM applications WHERE id=NEW.application_id FOR UPDATE;
 SELECT ac.candidate_user_id,ac.organization_id INTO s FROM application_context ac WHERE ac.id=a.id;
 IF NEW.new_state<>'expired' AND NOT EXISTS(SELECT 1 FROM retention_scopes WHERE id=a.retention_scope_id AND revoked_at IS NULL AND CURRENT_TIMESTAMP<access_until) THEN
  RAISE EXCEPTION 'expired application cannot be amended or reopened'; END IF;
 IF NEW.amends_event_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM application_events WHERE id=NEW.amends_event_id AND application_id=a.id) THEN
  RAISE EXCEPTION 'decision amendment must identify an earlier event on this application'; END IF;
 IF a.first_closed_at IS NOT NULL AND NEW.amends_event_id IS NULL THEN RAISE EXCEPTION 'closed participation cannot restart'; END IF;
 IF NEW.new_state='withdrawn' THEN
  IF NEW.actor_user_id IS DISTINCT FROM s.candidate_user_id THEN RAISE EXCEPTION 'withdrawal is candidate-controlled'; END IF;
 ELSIF NEW.new_state='expired' THEN
  IF CURRENT_TIMESTAMP<a.submitted_at+interval '90 days' OR a.first_closed_at IS NOT NULL THEN RAISE EXCEPTION 'unresolved deadline not reached'; END IF;
 ELSE
  IF NEW.actor_user_id=s.candidate_user_id OR NOT can_org(NEW.actor_user_id,s.organization_id,'decision_record') THEN
   RAISE EXCEPTION 'decision/stage actor not authorized or is applicant'; END IF;
 END IF;
 IF NEW.new_state IN ('selected','hired') AND NOT mandatory_stages_satisfied(a.id) THEN
  RAISE EXCEPTION 'required checks are incomplete and lack approved exceptions'; END IF;
 IF NEW.new_state='hired' AND a.status<>'selected' AND NEW.amends_event_id IS NULL THEN RAISE EXCEPTION 'Hired requires prior selection'; END IF;
 IF a.status='selected' AND NEW.amends_event_id IS NULL AND NEW.new_state NOT IN ('hired','rejected','withdrawn','expired') THEN
  RAISE EXCEPTION 'selected application cannot resume ordinary stages'; END IF;
 IF NEW.new_state='assessment' AND NOT EXISTS(SELECT 1 FROM assessment_invitations WHERE application_id=a.id AND cancelled_at IS NULL) THEN
  RAISE EXCEPTION 'stage entry requires an invitation, not a completed test'; END IF;
 IF NEW.new_state='interview' AND NOT EXISTS(SELECT 1 FROM interview_schedules WHERE application_id=a.id) THEN RAISE EXCEPTION 'interview appointment required'; END IF;
 IF NEW.new_state IN ('shortlisted','selected','hired','rejected') THEN
  IF NEW.source_referral_id IS NULL THEN SELECT id INTO NEW.source_referral_id FROM application_referrals WHERE application_id=a.id ORDER BY revision_number DESC LIMIT 1; END IF;
  IF NOT EXISTS(SELECT 1 FROM application_referrals WHERE id=NEW.source_referral_id AND application_id=a.id) THEN RAISE EXCEPTION 'decision source-history link mismatch'; END IF;
 END IF;
 firstclose:=a.first_closed_at;
 IF NEW.new_state IN ('hired','rejected','withdrawn','expired') AND firstclose IS NULL THEN
  firstclose:=CASE WHEN NEW.new_state='expired' THEN a.submitted_at+interval '90 days' ELSE CURRENT_TIMESTAMP END;
 END IF;
 UPDATE applications SET status=NEW.new_state,first_closed_at=firstclose WHERE id=a.id;
 IF firstclose IS NOT NULL THEN UPDATE retention_scopes SET first_closed_at=firstclose WHERE id=a.retention_scope_id; END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_assessment_data() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record; z record; maximum numeric; expected numeric; nextrev integer; marked integer; required integer;
BEGIN
 IF TG_TABLE_NAME='assessment_attempts' THEN
  SELECT i.*,av.duration_seconds,av.allowed_attempts,ac.candidate_user_id,ac.organization_id,ac.first_closed_at,s.access_until
   INTO x FROM assessment_invitations i JOIN assessment_versions av ON av.id=i.assessment_version_id
   JOIN application_context ac ON ac.id=i.application_id JOIN retention_scopes s ON s.id=ac.retention_scope_id
   WHERE i.id=NEW.invitation_id FOR UPDATE OF i;
  IF CURRENT_TIMESTAMP>=x.access_until THEN RAISE EXCEPTION 'attempt source access expired'; END IF;
  IF TG_OP='INSERT' THEN
   IF x.cancelled_at IS NOT NULL OR x.first_closed_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.expires_at OR CURRENT_TIMESTAMP>=x.access_until THEN
    RAISE EXCEPTION 'invitation/application is no longer eligible'; END IF;
   SELECT coalesce(max(attempt_number),0)+1 INTO nextrev FROM assessment_attempts WHERE invitation_id=NEW.invitation_id;
   IF NEW.attempt_number<>nextrev OR nextrev>x.allowed_attempts OR NEW.status<>'in_progress' THEN RAISE EXCEPTION 'attempt limit/order invalid'; END IF;
   IF EXISTS(SELECT 1 FROM assessment_attempts WHERE invitation_id=NEW.invitation_id AND status IN ('in_progress','interrupted')) THEN
    RAISE EXCEPTION 'an unfinished attempt already exists'; END IF;
   NEW.started_at:=CURRENT_TIMESTAMP;
   NEW.deadline_at:=NEW.started_at+make_interval(secs=>coalesce(x.accommodated_duration_seconds,x.duration_seconds));
  ELSE
   IF x.first_closed_at IS NOT NULL AND OLD.status IN ('in_progress','interrupted') AND NEW.status<>'cancelled' THEN RAISE EXCEPTION 'closed application cannot continue participation'; END IF;
   IF (NEW.invitation_id,NEW.attempt_number,NEW.operation_key,NEW.started_at,NEW.deadline_at)
     IS DISTINCT FROM (OLD.invitation_id,OLD.attempt_number,OLD.operation_key,OLD.started_at,OLD.deadline_at) THEN RAISE EXCEPTION 'attempt timing/version cannot reset'; END IF;
   IF OLD.status='finalized' THEN RAISE EXCEPTION 'finalized attempt cannot be rewritten'; END IF;
   IF NEW.status='submitted' THEN
    IF OLD.status NOT IN ('in_progress','interrupted') OR CURRENT_TIMESTAMP>NEW.deadline_at THEN RAISE EXCEPTION 'submission is late or already finalized'; END IF;
    NEW.submitted_at:=CURRENT_TIMESTAMP;
   ELSIF NEW.status='timed_out' THEN
    IF CURRENT_TIMESTAMP<NEW.deadline_at OR OLD.status NOT IN ('in_progress','interrupted') THEN RAISE EXCEPTION 'timeout deadline not reached'; END IF;
    NEW.submitted_at:=NEW.deadline_at;
   ELSIF NEW.status='finalized' THEN
    IF OLD.status NOT IN ('submitted','timed_out') OR NEW.submitted_at IS NULL THEN RAISE EXCEPTION 'submitted attempt required before final marking'; END IF;
    SELECT count(*) INTO required FROM assessment_questions WHERE assessment_version_id=x.assessment_version_id;
    SELECT count(DISTINCT a.question_id) INTO marked FROM assessment_answers a
      WHERE a.attempt_id=NEW.id AND EXISTS(SELECT 1 FROM assessment_grades g WHERE g.answer_id=a.id);
    IF marked<>required THEN RAISE EXCEPTION 'all required question marking must be complete'; END IF;
    NEW.finalized_at:=CURRENT_TIMESTAMP;
   ELSIF OLD.status IN ('submitted','timed_out','cancelled') THEN RAISE EXCEPTION 'submitted answers/attempt state are frozen';
   END IF;
  END IF;
  RETURN NEW;
 END IF;
 IF TG_TABLE_NAME='assessment_answers' THEN
  SELECT at.*,i.assessment_version_id,ac.first_closed_at,s.access_until INTO x FROM assessment_attempts at JOIN assessment_invitations i ON i.id=at.invitation_id
   JOIN application_context ac ON ac.id=i.application_id JOIN retention_scopes s ON s.id=ac.retention_scope_id WHERE at.id=NEW.attempt_id;
  IF x.status<>'in_progress' OR x.first_closed_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.deadline_at OR CURRENT_TIMESTAMP>=x.access_until THEN RAISE EXCEPTION 'attempt answers are closed'; END IF;
  IF NOT EXISTS(SELECT 1 FROM assessment_questions WHERE id=NEW.question_id AND assessment_version_id=x.assessment_version_id) THEN RAISE EXCEPTION 'answer question belongs to another assessment version'; END IF;
  IF TG_OP='UPDATE' AND (NEW.attempt_id,NEW.question_id) IS DISTINCT FROM (OLD.attempt_id,OLD.question_id) THEN RAISE EXCEPTION 'answer context cannot change'; END IF;
  RETURN NEW;
 END IF;
 IF TG_TABLE_NAME='grader_assignments' THEN
  SELECT ac.* INTO x FROM assessment_attempts at JOIN assessment_invitations i ON i.id=at.invitation_id JOIN application_context ac ON ac.id=i.application_id WHERE at.id=NEW.attempt_id;
  IF NEW.grader_user_id=x.candidate_user_id OR NEW.assigned_by=x.candidate_user_id
   OR NOT can_org(NEW.assigned_by,x.organization_id,'grading_assign') OR NOT can_org(NEW.grader_user_id,x.organization_id,'written_grade') THEN
   RAISE EXCEPTION 'grader assignment not authorized or is self-grading'; END IF;
  RETURN NEW;
 END IF;
 IF TG_TABLE_NAME='assessment_grades' THEN
  SELECT q.*,a.answer_text,a.attempt_id INTO x FROM assessment_answers a JOIN assessment_questions q ON q.id=a.question_id WHERE a.id=NEW.answer_id;
  SELECT ac.*,at.status AS attempt_status INTO y FROM assessment_attempts at JOIN assessment_invitations i ON i.id=at.invitation_id JOIN application_context ac ON ac.id=i.application_id WHERE at.id=x.attempt_id FOR UPDATE OF at;
  IF NOT EXISTS(SELECT 1 FROM retention_scopes WHERE id=y.retention_scope_id AND revoked_at IS NULL AND CURRENT_TIMESTAMP<access_until) THEN RAISE EXCEPTION 'grading source access expired'; END IF;
  IF y.attempt_status NOT IN ('submitted','timed_out','finalized') THEN RAISE EXCEPTION 'only submitted work may be graded'; END IF;
  IF NEW.points>x.max_points THEN RAISE EXCEPTION 'awarded points exceed the frozen maximum'; END IF;
  IF x.question_type='written' THEN
   IF NEW.marking_kind<>'human_written' OR NEW.grader_user_id=y.candidate_user_id OR NOT can_org(NEW.grader_user_id,y.organization_id,'written_grade') OR NOT EXISTS(SELECT 1 FROM grader_assignments WHERE attempt_id=x.attempt_id AND grader_user_id=NEW.grader_user_id) THEN
    RAISE EXCEPTION 'written answers require an assigned non-applicant human grader'; END IF;
  ELSE
   expected:=CASE WHEN x.answer_text=x.correct_option THEN x.max_points ELSE 0 END;
   IF NEW.marking_kind<>'deterministic_mcq' OR NEW.points<>expected THEN RAISE EXCEPTION 'MCQ score must follow the frozen answer key'; END IF;
  END IF;
  SELECT coalesce(max(revision_number),0)+1 INTO nextrev FROM assessment_grades WHERE answer_id=NEW.answer_id;
  IF nextrev=1 AND NEW.amends_id IS NOT NULL THEN RAISE EXCEPTION 'initial grade cannot amend another answer'; END IF;
  IF NEW.revision_number<>nextrev OR (nextrev>1 AND NOT EXISTS(SELECT 1 FROM assessment_grades WHERE id=NEW.amends_id AND answer_id=NEW.answer_id AND revision_number=nextrev-1)) THEN
   RAISE EXCEPTION 'grade amendment must preserve the prior revision'; END IF;
  RETURN NEW;
 END IF;
 IF TG_TABLE_NAME='assessment_releases' THEN
  SELECT ac.*,at.status AS attempt_status INTO x FROM assessment_attempts at JOIN assessment_invitations i ON i.id=at.invitation_id JOIN application_context ac ON ac.id=i.application_id WHERE at.id=NEW.attempt_id;
  IF NOT EXISTS(SELECT 1 FROM retention_scopes WHERE id=x.retention_scope_id AND revoked_at IS NULL AND CURRENT_TIMESTAMP<access_until) THEN RAISE EXCEPTION 'result release source expired'; END IF;
  IF x.attempt_status<>'finalized' OR NEW.released_by=x.candidate_user_id OR NOT can_org(NEW.released_by,x.organization_id,'result_release') THEN
   RAISE EXCEPTION 'release requires finalized marking and separate release permission'; END IF;
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_interview_event() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; nextrev integer;
BEGIN
 SELECT ac.* INTO x FROM interview_schedules i JOIN application_context ac ON ac.id=i.application_id WHERE i.id=NEW.interview_id;
 IF NOT EXISTS(SELECT 1 FROM retention_scopes WHERE id=x.retention_scope_id AND revoked_at IS NULL AND CURRENT_TIMESTAMP<access_until) THEN RAISE EXCEPTION 'interview source access expired'; END IF;
 IF NEW.event_type IN ('accepted','change_requested','declined') THEN
