  IF x.first_closed_at IS NOT NULL AND NEW.event_type<>'correction' THEN RAISE EXCEPTION 'closed interview participation cannot restart'; END IF;
 END IF;
 SELECT coalesce(max(revision_number),0)+1 INTO nextrev FROM interview_events WHERE interview_id=NEW.interview_id;
 IF NEW.revision_number<>nextrev THEN RAISE EXCEPTION 'interview event revision is stale'; END IF;
 IF NEW.event_type='correction' AND NOT EXISTS(SELECT 1 FROM interview_events WHERE id=NEW.amends_id AND interview_id=NEW.interview_id) THEN RAISE EXCEPTION 'interview correction must link earlier event'; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_timezone_names WHERE name=NEW.display_time_zone) THEN RAISE EXCEPTION 'unknown display time zone'; END IF;
 RETURN NEW;
END $$;

