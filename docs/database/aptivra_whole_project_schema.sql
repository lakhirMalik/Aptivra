 IF TG_TABLE_NAME='role_catalogue_versions' AND NOT EXISTS(SELECT 1 FROM role_criteria WHERE role_catalogue_version_id=NEW.id) THEN
  RAISE EXCEPTION 'role criteria required before publication';
 ELSIF TG_TABLE_NAME='vacancy_versions' THEN
  IF NOT EXISTS(SELECT 1 FROM role_catalogue_versions WHERE id=NEW.role_catalogue_version_id AND state='published')
   OR NOT EXISTS(SELECT 1 FROM vacancy_criteria WHERE vacancy_version_id=NEW.id)
   OR NOT EXISTS(SELECT 1 FROM vacancy_review_stages WHERE vacancy_version_id=NEW.id AND stage_type='review' AND is_required) THEN
    RAISE EXCEPTION 'published role, vacancy criteria and mandatory review policy required'; END IF;
 ELSIF TG_TABLE_NAME='practice_bank_versions' AND NOT EXISTS(SELECT 1 FROM practice_questions WHERE bank_version_id=NEW.id) THEN
  RAISE EXCEPTION 'reviewed practice questions required';
 ELSIF TG_TABLE_NAME='assessment_versions' AND NOT EXISTS(SELECT 1 FROM assessment_questions WHERE assessment_version_id=NEW.id) THEN
  RAISE EXCEPTION 'assessment questions required before publication';
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_document_data() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record; n bigint;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'cv_documents' THEN
  SELECT a.kind,s.purpose INTO x FROM stored_artifacts a JOIN retention_scopes s ON s.id=a.retention_scope_id WHERE a.id=NEW.artifact_id;
  IF x.kind<>'cv' OR x.purpose NOT IN ('one_off','saved_history','application') THEN RAISE EXCEPTION 'CV purpose/artifact mismatch'; END IF;
 WHEN 'processing_operations' THEN
  SELECT * INTO x FROM document_context WHERE document_id=NEW.cv_document_id;
  IF x.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.access_until THEN RAISE EXCEPTION 'document access expired'; END IF;
  IF TG_OP='INSERT' AND NEW.status<>'queued' THEN RAISE EXCEPTION 'new processing operation starts queued'; END IF;
  IF TG_OP='UPDATE' AND ((NEW.cv_document_id,NEW.manifest_id,NEW.operation_key,NEW.started_at,NEW.deadline_at)
   IS DISTINCT FROM (OLD.cv_document_id,OLD.manifest_id,OLD.operation_key,OLD.started_at,OLD.deadline_at)
   OR OLD.finished_at IS NOT NULL) THEN RAISE EXCEPTION 'processing identity/deadline/final outcome cannot be rewritten'; END IF;
  IF NEW.status IN ('extracting','ready','needs_clarification') AND coalesce((SELECT result FROM virus_scan_logs
   WHERE processing_operation_id=NEW.id ORDER BY scanned_at DESC,id DESC LIMIT 1),'unavailable')<>'clean' THEN RAISE EXCEPTION 'only a verified clean scan enables extraction'; END IF;
  IF NEW.status='ready' AND NOT EXISTS(SELECT 1 FROM cv_extractions WHERE processing_operation_id=NEW.id AND result_state='ready') THEN RAISE EXCEPTION 'ready requires complete extracted evidence'; END IF;
 WHEN 'cv_extractions' THEN
  IF coalesce((SELECT result FROM virus_scan_logs WHERE processing_operation_id=NEW.processing_operation_id ORDER BY scanned_at DESC,id DESC LIMIT 1),'unavailable')<>'clean'
   OR NOT EXISTS(SELECT 1 FROM processing_operations WHERE id=NEW.processing_operation_id AND status='extracting' AND CURRENT_TIMESTAMP<deadline_at) THEN
   RAISE EXCEPTION 'extraction requires a verified clean scan'; END IF;
 WHEN 'cv_passages' THEN
  SELECT total_pages INTO n FROM cv_extractions WHERE id=NEW.cv_extraction_id;
  IF NEW.page_number>n THEN RAISE EXCEPTION 'passage page exceeds source page count'; END IF;
 WHEN 'cv_extraction_corrections' THEN
  SELECT p.cv_extraction_id,d.owner_user_id,d.organization_id INTO x FROM cv_passages p
   JOIN cv_extractions e ON e.id=p.cv_extraction_id JOIN processing_operations op ON op.id=e.processing_operation_id
   JOIN document_context d ON d.document_id=op.cv_document_id WHERE p.id=NEW.source_passage_id;
  IF NEW.cv_claim_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM cv_claims c JOIN cv_passages p ON p.id=c.source_passage_id WHERE c.id=NEW.cv_claim_id AND p.cv_extraction_id=x.cv_extraction_id) THEN
   RAISE EXCEPTION 'correction claim belongs to another extraction'; END IF;
  IF NEW.supersedes_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM cv_extraction_corrections c JOIN cv_passages p ON p.id=c.source_passage_id WHERE c.id=NEW.supersedes_id AND p.cv_extraction_id=x.cv_extraction_id) THEN
   RAISE EXCEPTION 'correction amendment cannot rewrite another document version'; END IF;
  IF NEW.requested_by<>x.owner_user_id AND NOT can_org(NEW.requested_by,x.organization_id,'review_complete') THEN
   RAISE EXCEPTION 'correction requester not authorized'; END IF;
  IF NEW.status<>'pending' AND NOT ((x.organization_id IS NULL AND NEW.reviewed_by=x.owner_user_id)
    OR can_org(NEW.reviewed_by,x.organization_id,'review_complete')) THEN RAISE EXCEPTION 'correction resolution not authorized'; END IF;
  IF TG_OP='UPDATE' AND (OLD.status<>'pending' OR (NEW.source_passage_id,NEW.cv_claim_id,NEW.requested_by,NEW.earlier_value,NEW.proposed_value,NEW.request_reason)
      IS DISTINCT FROM (OLD.source_passage_id,OLD.cv_claim_id,OLD.requested_by,OLD.earlier_value,OLD.proposed_value,OLD.request_reason)) THEN
   RAISE EXCEPTION 'preserve correction request; append a later amendment'; END IF;
 WHEN 'evidence_comparisons' THEN
  IF NOT EXISTS(SELECT 1 FROM cv_extractions e JOIN processing_operations op ON op.id=e.processing_operation_id
   JOIN document_context d ON d.document_id=op.cv_document_id WHERE e.id=NEW.cv_extraction_id AND d.revoked_at IS NULL AND CURRENT_TIMESTAMP<d.access_until) THEN
   RAISE EXCEPTION 'comparison evidence is expired'; END IF;
  IF NEW.role_catalogue_version_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM role_catalogue_versions WHERE id=NEW.role_catalogue_version_id AND state='published') THEN
   RAISE EXCEPTION 'private comparison requires published role criteria'; END IF;
  IF NEW.vacancy_version_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vacancy_versions WHERE id=NEW.vacancy_version_id AND state='published') THEN
   RAISE EXCEPTION 'comparison requires a published vacancy version'; END IF;
 WHEN 'comparison_criteria_matches' THEN
  SELECT * INTO x FROM evidence_comparisons WHERE id=NEW.evidence_comparison_id;
  IF x.state<>'building' THEN RAISE EXCEPTION 'criterion results are frozen after report completion'; END IF;
  IF NEW.role_criterion_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM role_criteria WHERE id=NEW.role_criterion_id AND role_catalogue_version_id=x.role_catalogue_version_id) THEN
   RAISE EXCEPTION 'role criterion belongs to another comparison version'; END IF;
  IF NEW.vacancy_criterion_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vacancy_criteria WHERE id=NEW.vacancy_criterion_id AND vacancy_version_id=x.vacancy_version_id) THEN
   RAISE EXCEPTION 'vacancy criterion belongs to another comparison version'; END IF;
 WHEN 'match_evidence' THEN
  SELECT ec.cv_extraction_id INTO n FROM comparison_criteria_matches cm JOIN evidence_comparisons ec ON ec.id=cm.evidence_comparison_id WHERE cm.id=NEW.criterion_match_id;
  IF NOT EXISTS(SELECT 1 FROM cv_claims c JOIN cv_passages p ON p.id=c.source_passage_id WHERE c.id=NEW.cv_claim_id AND p.cv_extraction_id=n) THEN RAISE EXCEPTION 'claim belongs to another extraction'; END IF;
 END CASE;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_private_data() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record; n bigint; ownerid bigint; scopeid bigint;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'saved_preparation_versions' THEN
  SELECT * INTO x FROM retention_scopes WHERE id=NEW.retention_scope_id;
  SELECT * INTO y FROM document_context WHERE document_id=NEW.cv_document_id;
  IF x.purpose<>'saved_history' OR x.owner_user_id<>NEW.candidate_user_id OR y.retention_scope_id<>x.id
    OR CURRENT_TIMESTAMP>=x.access_until OR x.revoked_at IS NOT NULL THEN RAISE EXCEPTION 'saved history purpose/owner/source mismatch'; END IF;
  IF NOT entitled(NEW.candidate_user_id,NULL,'saved_history') THEN RAISE EXCEPTION 'history entitlement required'; END IF;
  IF NOT EXISTS(SELECT 1 FROM stored_artifacts WHERE id=NEW.report_artifact_id AND retention_scope_id=x.id AND kind='report') THEN
   RAISE EXCEPTION 'history report artifact must share the retained purpose'; END IF;
  IF NOT EXISTS(SELECT 1 FROM evidence_comparisons ec JOIN cv_extractions ex ON ex.id=ec.cv_extraction_id
   JOIN processing_operations op ON op.id=ex.processing_operation_id WHERE ec.id=NEW.comparison_id
   AND op.cv_document_id=NEW.cv_document_id AND ec.role_catalogue_version_id IS NOT NULL AND ec.state='ready') THEN
   RAISE EXCEPTION 'history comparison/source mismatch'; END IF;
 WHEN 'history_renewals' THEN
  SELECT * INTO x FROM saved_preparation_versions WHERE id=NEW.saved_version_id FOR UPDATE;
  SELECT * INTO y FROM retention_scopes WHERE id=x.retention_scope_id FOR UPDATE;
  IF NEW.actor_user_id<>x.candidate_user_id OR y.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=y.access_until
   OR NOT entitled(NEW.actor_user_id,NULL,'saved_history') THEN RAISE EXCEPTION 'history is expired, unowned or not entitled'; END IF;
  NEW.renewed_at:=CURRENT_TIMESTAMP;
  UPDATE retention_scopes SET saved_or_renewed_at=NEW.renewed_at WHERE id=y.id;
 WHEN 'practice_sessions' THEN
  SELECT * INTO x FROM retention_scopes WHERE id=NEW.retention_scope_id;
  IF x.purpose<>'one_off' OR x.owner_user_id IS NULL OR x.organization_id IS NOT NULL
   OR x.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.access_until
   OR NOT EXISTS(SELECT 1 FROM practice_bank_versions WHERE id=NEW.bank_version_id AND state='published') THEN
    RAISE EXCEPTION 'private practice requires an accessible owned purpose and reviewed bank'; END IF;
 WHEN 'practice_responses' THEN
  SELECT * INTO x FROM practice_sessions WHERE id=NEW.practice_session_id;
  IF x.status<>'in_progress' OR CURRENT_TIMESTAMP>=x.deadline_at OR NOT EXISTS(SELECT 1 FROM practice_questions
   WHERE id=NEW.practice_question_id AND bank_version_id=x.bank_version_id AND options_json ? NEW.selected_option) THEN
   RAISE EXCEPTION 'invalid question/answer or expired private attempt'; END IF;
 WHEN 'learning_guidance' THEN
  SELECT * INTO x FROM retention_scopes WHERE id=NEW.retention_scope_id;
  IF x.purpose NOT IN ('one_off','saved_history') OR x.owner_user_id IS NULL OR x.organization_id IS NOT NULL THEN
   RAISE EXCEPTION 'guidance is private candidate preparation'; END IF;
  IF x.revoked_at IS NOT NULL OR CURRENT_TIMESTAMP>=x.access_until THEN RAISE EXCEPTION 'guidance purpose expired'; END IF;
  IF NEW.comparison_id IS NOT NULL THEN
   SELECT d.owner_user_id INTO ownerid FROM evidence_comparisons ec JOIN cv_extractions e ON e.id=ec.cv_extraction_id
    JOIN processing_operations op ON op.id=e.processing_operation_id JOIN document_context d ON d.document_id=op.cv_document_id
    WHERE ec.id=NEW.comparison_id AND d.revoked_at IS NULL AND CURRENT_TIMESTAMP<d.access_until;
   IF ownerid IS DISTINCT FROM x.owner_user_id THEN RAISE EXCEPTION 'guidance comparison owner mismatch'; END IF;
  END IF;
  IF NEW.practice_session_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM practice_sessions ps JOIN retention_scopes s ON s.id=ps.retention_scope_id
   WHERE ps.id=NEW.practice_session_id AND s.owner_user_id=x.owner_user_id AND s.revoked_at IS NULL AND CURRENT_TIMESTAMP<s.access_until) THEN RAISE EXCEPTION 'guidance practice owner mismatch'; END IF;
 WHEN 'guidance_resources' THEN
  SELECT rv.job_family_id INTO n FROM learning_guidance g JOIN role_catalogue_versions rv ON rv.id=g.role_catalogue_version_id WHERE g.id=NEW.guidance_id;
  IF NOT EXISTS(SELECT 1 FROM learning_resources WHERE id=NEW.learning_resource_id AND job_family_id=n) THEN RAISE EXCEPTION 'guidance resource role mismatch'; END IF;
 END CASE;
 RETURN NEW;
END $$;

CREATE FUNCTION maintain_comparison() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE total integer; supported integer; actual integer;
BEGIN
 IF TG_OP='UPDATE' AND OLD.state<>'building' THEN RAISE EXCEPTION 'completed comparison is immutable'; END IF;
 IF NEW.role_catalogue_version_id IS NOT NULL THEN SELECT count(*) INTO total FROM role_criteria WHERE role_catalogue_version_id=NEW.role_catalogue_version_id;
 ELSE SELECT count(*) INTO total FROM vacancy_criteria WHERE vacancy_version_id=NEW.vacancy_version_id; END IF;
 SELECT count(*),count(*) FILTER(WHERE evidence_status='supported') INTO actual,supported
 FROM comparison_criteria_matches WHERE evidence_comparison_id=NEW.id;
 IF TG_OP='INSERT' THEN
  IF NEW.coverage_denominator<0 OR NEW.supported_numerator<0 OR NEW.supported_numerator>NEW.coverage_denominator THEN RAISE EXCEPTION 'invalid coverage counts'; END IF;
 ELSE
  IF (NEW.cv_extraction_id,NEW.role_catalogue_version_id,NEW.vacancy_version_id,NEW.manifest_id) IS DISTINCT FROM
     (OLD.cv_extraction_id,OLD.role_catalogue_version_id,OLD.vacancy_version_id,OLD.manifest_id) THEN RAISE EXCEPTION 'comparison context is immutable'; END IF;
 END IF;
 IF NEW.state='ready' AND (actual<>total OR total=0) THEN RAISE EXCEPTION 'complete criterion-level results required before ready'; END IF;
 NEW.coverage_denominator:=total; NEW.supported_numerator:=supported;
 RETURN NEW;
END $$;
