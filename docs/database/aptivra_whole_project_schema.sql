-- Ensure every FK has a leading non-partial index. Reuse PK/unique indexes.
DO $idx$
DECLARE c record; cols text; colids smallint[];
BEGIN
 FOR c IN SELECT * FROM pg_constraint WHERE contype='f' AND connamespace='aptivra_design'::regnamespace LOOP
  IF NOT EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid=c.conrelid AND i.indisvalid
    AND i.indpred IS NULL AND ARRAY(SELECT v FROM unnest(i.indkey::smallint[]) WITH ORDINALITY k(v,pos)
     WHERE pos<=cardinality(c.conkey) ORDER BY pos)=c.conkey) THEN
   SELECT string_agg(quote_ident(a.attname),',' ORDER BY u.ord) INTO cols
   FROM unnest(c.conkey) WITH ORDINALITY u(attnum,ord)
   JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=u.attnum;
   EXECUTE format('CREATE INDEX %I ON %s (%s)','ix_fk_'||substr(md5(c.conrelid::regclass::text||cols),1,18),c.conrelid::regclass,cols);
  END IF;
 END LOOP;
END $idx$;
