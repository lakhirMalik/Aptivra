CREATE FUNCTION compute_retention() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
BEGIN
 IF TG_OP='DELETE' THEN
  IF CURRENT_TIMESTAMP < OLD.purge_after THEN RAISE EXCEPTION 'scope is not due for purge'; END IF;
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' THEN
  IF OLD.processing_deadline IS NOT NULL AND NEW.processing_deadline IS DISTINCT FROM OLD.processing_deadline THEN
   RAISE EXCEPTION 'in-progress deadline is pinned, not reset by a page view'; END IF;
  IF (NEW.purpose,NEW.owner_user_id,NEW.organization_id,NEW.started_at) IS DISTINCT FROM
     (OLD.purpose,OLD.owner_user_id,OLD.organization_id,OLD.started_at) THEN
    RAISE EXCEPTION 'retention identity is immutable'; END IF;
  IF OLD.completed_at IS NOT NULL AND NEW.completed_at IS DISTINCT FROM OLD.completed_at THEN
    RAISE EXCEPTION 'completion cannot restart retention'; END IF;
  IF OLD.first_closed_at IS NOT NULL AND NEW.first_closed_at IS DISTINCT FROM OLD.first_closed_at THEN
    RAISE EXCEPTION 'first closure cannot be restarted'; END IF;
  IF NEW.purpose='saved_history' AND NEW.saved_or_renewed_at IS DISTINCT FROM OLD.saved_or_renewed_at
     AND pg_trigger_depth()<2 THEN RAISE EXCEPTION 'history renewal requires an explicit renewal event'; END IF;
 END IF;
 IF NEW.completed_at>CURRENT_TIMESTAMP OR NEW.saved_or_renewed_at>CURRENT_TIMESTAMP OR NEW.first_closed_at>CURRENT_TIMESTAMP THEN
  RAISE EXCEPTION 'future completion/save/closure cannot extend retention'; END IF;
 CASE NEW.purpose
 WHEN 'one_off' THEN
  IF NEW.completed_at IS NULL THEN
   IF NEW.processing_deadline IS NULL OR NEW.processing_deadline<=NEW.started_at THEN
    RAISE EXCEPTION 'bounded in-progress deadline required'; END IF;
   NEW.access_until:=NEW.processing_deadline;
  ELSE NEW.access_until:=NEW.completed_at+interval '24 hours'; END IF;
  NEW.purge_after:=NEW.access_until;
 WHEN 'saved_history' THEN
  IF NEW.saved_or_renewed_at IS NULL THEN RAISE EXCEPTION 'explicit save time required'; END IF;
  NEW.access_until:=NEW.saved_or_renewed_at+interval '90 days'; NEW.purge_after:=NEW.access_until;
 WHEN 'application' THEN
  IF NEW.first_closed_at IS NOT NULL AND NEW.first_closed_at<NEW.started_at+interval '90 days' THEN
   NEW.access_until:=NEW.first_closed_at+interval '30 days'; NEW.purge_after:=NEW.access_until;
  ELSE NEW.access_until:=NEW.started_at+interval '90 days';
   NEW.purge_after:=NEW.started_at+interval '120 days'; END IF;
 ELSE
  IF NEW.access_until IS NULL OR NEW.purge_after IS NULL THEN
   RAISE EXCEPTION 'supporting-record deadlines must be configured under TBD-06'; END IF;
 END CASE;
 IF NEW.revoked_at IS NOT NULL AND NEW.purpose IN ('one_off','saved_history','export') THEN
  NEW.access_until:=least(NEW.access_until,NEW.revoked_at);
  NEW.purge_after:=least(NEW.purge_after,NEW.revoked_at);
 END IF;
 RETURN NEW;
END $$;
