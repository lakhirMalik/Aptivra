CREATE FUNCTION report_delivery() RETURNS trigger LANGUAGE plpgsql
 SET search_path=aptivra_design,pg_catalog AS $$
DECLARE x record; y record;
BEGIN
 SELECT s.*,a.kind INTO x FROM stored_artifacts a JOIN retention_scopes s ON s.id=a.retention_scope_id WHERE a.id=NEW.artifact_id;
 SELECT p.user_id,r.status INTO y FROM report_credit_reservations r JOIN report_credit_periods p ON p.id=r.period_id WHERE r.id=NEW.credit_reservation_id;
 IF x.kind<>'report' OR x.purpose<>'one_off' OR x.owner_user_id IS DISTINCT FROM y.user_id THEN RAISE EXCEPTION 'report owner/purpose/credit mismatch'; END IF;
 IF NEW.state='ready' THEN
  IF y.status<>'reserved' THEN RAISE EXCEPTION 'ready delivery requires an active reservation'; END IF;
  IF NOT EXISTS(SELECT 1 FROM evidence_comparisons ec JOIN cv_extractions e ON e.id=ec.cv_extraction_id
   JOIN processing_operations op ON op.id=e.processing_operation_id JOIN document_context d ON d.document_id=op.cv_document_id
   WHERE ec.id=NEW.comparison_id AND ec.state='ready' AND d.retention_scope_id=x.id)
