CREATE SCHEMA aptivra_design;
SET LOCAL search_path = aptivra_design, pg_catalog;
CREATE DOMAIN nonempty_text AS text CHECK (VALUE ~ '[^[:space:]]');
CREATE DOMAIN sha256_text AS text CHECK (VALUE ~ '^[0-9a-f]{64}$');
CREATE DOMAIN web_url AS text CHECK (VALUE ~ '^https?://[^[:space:]]+$');
CREATE FUNCTION has_text(text) RETURNS boolean LANGUAGE sql IMMUTABLE
 AS $$ SELECT coalesce($1 ~ '[^[:space:]]', false) $$;
-- C01 / UC-01,02,03,32,35
CREATE TABLE users (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
display_name nonempty_text NOT NULL,
email text UNIQUE CHECK (email = lower(btrim(email))),
password_hash text,
email_verified_at timestamptz,
is_platform_admin boolean NOT NULL DEFAULT false,
status text NOT NULL DEFAULT 'unverified' CHECK (status IN ('unverified','active','suspended','closed')),
last_active_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
inactivity_notice_at timestamptz,
closed_at timestamptz,
created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
CHECK (status = 'closed' OR (email IS NOT NULL AND password_hash IS NOT NULL)),
CHECK ((status = 'closed') = (closed_at IS NOT NULL))
);

